const fs = require('fs');
const path = require('path');

/**
 * Inventory of the shipped dashboard tree — `dashboards/inventory.json`.
 *
 *   {
 *     "version": 1,
 *     "bundles": [ { "id": "home", "path": "system/home", "unit": "bundle" },
 *                  { "id": "top_scripts", "path": "top/top_scripts.sql", "unit": "file" }, … ],
 *     "folders": [ "changelog", "modules", "modules/docs", … ]
 *   }
 *
 * `bundles` lists every dashboard of the tree, path relative to `dashboards/`:
 * each directory with a `manifest.json` (`unit: "bundle"`, id = directory name)
 * and each `.sql` file directly in a grouping folder (`unit: "file"`, id = file
 * name without `.sql`; never on the top level, never inside a bundle). An
 * entry without `unit` is a bundle (inventories written before file units).
 * `folders` lists every other directory of the tree (grouping and rubric
 * folders, with or without `folder.json`). Both sorted by path, so the file is
 * stable and diffs stay small.
 *
 * The file is generated by the maintainer tool `tools/dashboards/inventory.mjs`
 * (`--write`, `--check`) and shipped with every release. At runtime it is the
 * reference for "what does this release ship": the dashboard cleanup tells
 * leftovers of older layouts apart from shipped bundles without needing `.git`
 * (Docker and ZIP installations have none).
 */

const INVENTORY_FILE = 'inventory.json';
const FORMAT_VERSION = 1;
// Safety net against symlink loops; the shipped tree is far shallower.
const MAX_DEPTH = 8;

function isBundleDir(absDir) {
  try {
    return fs.statSync(path.join(absDir, 'manifest.json')).isFile();
  } catch {
    return false;
  }
}

/**
 * Walks `dashboardsDir` and returns the inventory object (not written).
 * Dot entries are skipped, bundle directories are not descended into.
 */
function buildInventory(dashboardsDir) {
  const bundles = [];
  const folders = [];
  const walk = (rel, depth) => {
    const abs = path.join(dashboardsDir, rel);
    let entries;
    try {
      entries = fs.readdirSync(abs, { withFileTypes: true });
    } catch (err) {
      if (err.code === 'ENOENT') return;
      throw err;
    }
    for (const e of entries) {
      if (e.name.startsWith('.')) continue;
      const childRel = rel ? `${rel}/${e.name}` : e.name;
      if (!e.isDirectory()) {
        if (rel && e.isFile() && e.name.endsWith('.sql')) {
          bundles.push({ id: e.name.slice(0, -4), path: childRel, unit: 'file' });
        }
        continue;
      }
      if (isBundleDir(path.join(abs, e.name))) {
        bundles.push({ id: e.name, path: childRel, unit: 'bundle' });
      } else {
        folders.push(childRel);
        if (depth < MAX_DEPTH) walk(childRel, depth + 1);
      }
    }
  };
  walk('', 0);
  bundles.sort((a, b) => (a.path < b.path ? -1 : a.path > b.path ? 1 : 0));
  folders.sort();
  return { version: FORMAT_VERSION, bundles, folders };
}

/** Serialized form, byte-stable for `--check`. */
function serializeInventory(inventory) {
  return JSON.stringify(inventory, null, 2) + '\n';
}

function inventoryPath(dashboardsDir) {
  return path.join(dashboardsDir, INVENTORY_FILE);
}

/**
 * Reads `dashboards/inventory.json`. Returns null when the file is missing or
 * unusable — callers must then treat the tree as unknown, never as empty.
 */
function readInventory(dashboardsDir) {
  let parsed;
  try {
    parsed = JSON.parse(fs.readFileSync(inventoryPath(dashboardsDir), 'utf-8'));
  } catch {
    return null;
  }
  if (!parsed || !Array.isArray(parsed.bundles) || !Array.isArray(parsed.folders)) return null;
  return {
    version: parsed.version,
    bundles: parsed.bundles
      .filter(b => b && typeof b.id === 'string' && typeof b.path === 'string')
      .map(b => ({ id: b.id, path: b.path, unit: b.unit === 'file' ? 'file' : 'bundle' })),
    folders: parsed.folders.filter(f => typeof f === 'string'),
  };
}

/**
 * Names this release ships: every dashboard id of the dashboard inventory
 * (bundles and file units) plus every internal template name of
 * `queries/inventory.json`. A missing inventory falls back to the live shipped
 * tree, so a broken installation never turns an old copy of a shipped query
 * into a user query. Defaults to the configured template directories.
 */
function knownNames({ dashboardsDir, queriesDir } = {}) {
  // Lazy: template-inventory delegates its dashboards kind to this module.
  const templateInventory = require('./template-inventory');
  const templates = require('../config/environment').templates;
  const dDir = dashboardsDir || templates.dashboardsDir;
  const qDir = queriesDir || templates.queriesDir;
  const dashboards = readInventory(dDir) || buildInventory(dDir);
  const queries = templateInventory.readInventory('queries', qDir)
    || templateInventory.buildInventory('queries', qDir);
  return new Set([...dashboards.bundles.map(b => b.id), ...queries.queries.map(q => q.name)]);
}

/**
 * "Unknown name": shipped by this release neither as a dashboard nor as an
 * internal template. Decides whether a file at an old location is the user's
 * own query (unknown) or a leftover copy of a shipped one.
 */
function isUnknownName(name, known = knownNames()) {
  return !known.has(name);
}

/**
 * Differences between two inventories as human-readable lines
 * (`+ bundle system/home`, `+ bundle top/top_scripts.sql`, `- folder changelog`);
 * empty when equal.
 */
function diffInventories(expected, actual) {
  const key = b => `${b.path}\t${b.id}\t${b.unit || 'bundle'}`;
  const lines = [];
  const diffSets = (label, exp, act) => {
    const e = new Set(exp);
    const a = new Set(act);
    for (const x of a) if (!e.has(x)) lines.push(`+ ${label} ${x.split('\t')[0]}`);
    for (const x of e) if (!a.has(x)) lines.push(`- ${label} ${x.split('\t')[0]}`);
  };
  diffSets('bundle', expected.bundles.map(key), actual.bundles.map(key));
  diffSets('folder', expected.folders, actual.folders);
  return lines.sort();
}

module.exports = {
  INVENTORY_FILE,
  FORMAT_VERSION,
  buildInventory,
  serializeInventory,
  inventoryPath,
  readInventory,
  diffInventories,
  knownNames,
  isUnknownName,
};
