/**
 * HTML page for `format=mermaid`: the diagram source sits HTML-escaped in a
 * `<pre>`, pele (served by this API under /api/assets/pele.js, no CDN) draws it
 * in the browser. Links, images and HTML labels stay off; the page script is
 * static — no data ever reaches it except as the text content of the `<pre>`.
 * Colours come from the fm-lab theme tokens (light / dark).
 */

const { MERMAID_SOURCE_LIMIT } = require('../../config/constants');

/** Path of the browser bundle; see routes/assets.routes.js. */
const PELE_ASSET_PATH = '/api/assets/pele.js';

const LIGHT = {
  page: '#f9f9f9',
  card: '#ffffff',
  text: '#213547',
  muted: '#555555',
  surface: '#f9f9f9',
  surface2: '#f0f0f0',
  border: '#c0c0c0',
  accent: '#646cff',
  error: '#b91c1c',
};

const DARK = {
  page: '#0f1115',
  card: '#232831',
  text: '#e6e8ec',
  muted: '#b8bdc7',
  surface: '#1a1d23',
  surface2: '#22262e',
  border: '#444a55',
  accent: '#8a91ff',
  error: '#f87171',
};

function escapeHtml(text) {
  if (text === null || text === undefined) return '';
  const map = { '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#039;' };
  return String(text).replace(/[&<>"']/g, (m) => map[m]);
}

function tokens(t) {
  return [
    `--page:${t.page}`, `--card:${t.card}`, `--text:${t.text}`, `--muted:${t.muted}`,
    `--border:${t.border}`, `--error:${t.error}`,
    `--pele-bg:${t.card}`, `--pele-fg:${t.text}`, `--pele-muted:${t.muted}`,
    `--pele-line:${t.muted}`, `--pele-surface:${t.surface}`, `--pele-surface-alt:${t.surface2}`,
    `--pele-border:${t.border}`, `--pele-accent:${t.accent}`, '--pele-radius:4px',
  ].join(';');
}

/**
 * Theme CSS: `dark` forces the dark tokens; `default` follows the system
 * setting; every other theme (forest, neutral) is light.
 */
function themeCss(theme) {
  if (theme === 'dark') return `:root{${tokens(DARK)};color-scheme:dark}`;
  if (theme === 'default' || !theme) {
    return `:root{${tokens(LIGHT)};color-scheme:light dark}`
      + `@media (prefers-color-scheme: dark){:root{${tokens(DARK)}}}`;
  }
  return `:root{${tokens(LIGHT)};color-scheme:light}`;
}

/** Version suffix of the asset URL (cache busting across pele updates). */
let peleVersion;
function getPeleVersion() {
  if (peleVersion === undefined) {
    try {
      peleVersion = require('pele/package.json').version;
    } catch {
      peleVersion = '';
    }
  }
  return peleVersion;
}

/**
 * @param {string} source - Mermaid source
 * @param {Object} [options]
 * @param {string} [options.title]
 * @param {string} [options.description]
 * @param {string} [options.theme] - default | dark | forest | neutral
 * @returns {string} complete HTML document
 */
function buildHtmlPage(source, options = {}) {
  const title = options.title || 'FileMaker Diagram';
  const description = options.description || '';
  const version = getPeleVersion();
  const assetUrl = version ? `${PELE_ASSET_PATH}?v=${encodeURIComponent(version)}` : PELE_ASSET_PATH;

  return `<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="UTF-8">
<meta name="viewport" content="width=device-width, initial-scale=1.0">
<title>${escapeHtml(title)}</title>
<style>
${themeCss(options.theme)}
*{box-sizing:border-box}
body{margin:0;padding:20px;background:var(--page);color:var(--text);font:14px/1.5 system-ui,-apple-system,"Segoe UI",Roboto,sans-serif}
.container{max-width:1600px;margin:0 auto;background:var(--card);border:1px solid var(--border);border-radius:8px;padding:24px}
h1{font-size:1.4rem;margin:0 0 8px}
.description{color:var(--muted);margin:0 0 20px}
.diagram{position:relative;overflow-x:auto;min-height:120px}
pre.mermaid{margin:0;white-space:pre-wrap;font:12px/1.4 ui-monospace,SFMono-Regular,Menlo,monospace;color:var(--muted)}
.error{color:var(--error);margin:12px 0 0;white-space:pre-wrap}
.footer{margin-top:20px;padding-top:12px;border-top:1px solid var(--border);color:var(--muted);font-size:12px;text-align:center}
</style>
</head>
<body>
<div class="container">
<h1>${escapeHtml(title)}</h1>
${description ? `<p class="description">${escapeHtml(description)}</p>\n` : ''}<div class="diagram" id="diagram"><pre class="mermaid" id="source">${escapeHtml(source)}</pre></div>
<p class="error" id="error" hidden></p>
<div class="footer">Generated by FM-Lab REST API</div>
</div>
<script src="${escapeHtml(assetUrl)}"></script>
<script>
(function () {
  var box = document.getElementById('diagram');
  var pre = document.getElementById('source');
  var out = document.getElementById('error');
  function fail(err) {
    var msg = err && err.message ? err.message : String(err);
    if (err && err.line) msg += ' (line ' + err.line + ')';
    out.textContent = 'Diagram could not be drawn: ' + msg;
    out.hidden = false;
    if (!pre.isConnected) box.appendChild(pre);
  }
  if (typeof pele === 'undefined') { fail('renderer not loaded (${PELE_ASSET_PATH})'); return; }
  var text = pre.textContent;
  try {
    pre.remove();
    var mounted = pele.mount(box, text, { links: false, images: false, limit: ${MERMAID_SOURCE_LIMIT}, zoom: 'auto', onError: fail });
    if (mounted && mounted.error !== undefined) fail(mounted.error);
  } catch (err) {
    fail(err);
  }
})();
</script>
</body>
</html>`;
}

module.exports = { buildHtmlPage, escapeHtml, PELE_ASSET_PATH };
